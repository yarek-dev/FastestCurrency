create table public.knowledge_sources (
    id bigint generated by default as identity primary key,
    url text not null unique check (url ~ '^https?://[^[:space:]]+$'),
    title text not null check (btrim(title) <> ''),
    kind text not null check (kind in ('page', 'notice', 'attachment')),
    body text,
    source_modified_at timestamptz,
    fetched_at timestamptz not null default now(),
    content_sha256 text check (content_sha256 ~ '^[0-9a-f]{64}$')
);

create table public.knowledge_chunks (
    id bigint generated by default as identity primary key,
    source_id bigint not null references public.knowledge_sources (id) on delete cascade,
    position integer not null check (position >= 0),
    heading text,
    body text not null check (btrim(body) <> ''),
    search_text tsvector generated always as (
        to_tsvector('pg_catalog.russian'::regconfig, coalesce(heading, '') || ' ' || body)
    ) stored,
    unique (source_id, position)
);

-- Each price column in a source can be imported as a separate record with a stable key.
create table public.knowledge_tariffs (
    id bigint generated by default as identity primary key,
    source_id bigint not null references public.knowledge_sources (id) on delete cascade,
    source_key text not null check (btrim(source_key) <> ''),
    service_name text not null check (btrim(service_name) <> ''),
    section text,
    audience text not null default 'not_stated' check (btrim(audience) <> ''),
    unit text,
    price_label text not null check (btrim(price_label) <> ''),
    source_value text not null check (btrim(source_value) <> ''),
    price_type text not null check (price_type in ('fixed', 'from', 'range')),
    amount numeric(14, 2) not null check (amount >= 0 and amount < 'Infinity'::numeric),
    max_amount numeric(14, 2),
    currency text check (currency ~ '^[A-Z]{3}$'),
    effective_date date,
    search_text tsvector generated always as (
        to_tsvector('pg_catalog.russian'::regconfig, service_name || ' ' || coalesce(section, ''))
    ) stored,
    unique (source_id, source_key),
    constraint knowledge_tariff_amount_range check (
        (price_type = 'range' and max_amount is not null and max_amount >= amount and max_amount < 'Infinity'::numeric)
        or (price_type <> 'range' and max_amount is null)
    )
);

create index knowledge_chunks_search_idx on public.knowledge_chunks using gin (search_text);
create index knowledge_tariffs_search_idx on public.knowledge_tariffs using gin (search_text);
create index knowledge_tariffs_audience_idx on public.knowledge_tariffs (audience);

alter table public.knowledge_sources enable row level security;
alter table public.knowledge_chunks enable row level security;
alter table public.knowledge_tariffs enable row level security;

revoke all on table public.knowledge_sources, public.knowledge_chunks, public.knowledge_tariffs
    from public, anon, authenticated;
revoke all on sequence public.knowledge_sources_id_seq, public.knowledge_chunks_id_seq, public.knowledge_tariffs_id_seq
    from public, anon, authenticated;
grant select, insert, update, delete on table public.knowledge_sources, public.knowledge_chunks, public.knowledge_tariffs
    to service_role;
grant usage, select on sequence public.knowledge_sources_id_seq, public.knowledge_chunks_id_seq, public.knowledge_tariffs_id_seq
    to service_role;
