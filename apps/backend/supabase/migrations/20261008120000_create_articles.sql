-- Supabase applies migrations inside a transaction.
create table public.articles (
    id bigint generated by default as identity not null,
    title text not null,
    body text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint articles_pkey primary key (id)
);

create index articles_updated_at_idx
    on public.articles (updated_at desc);

-- Keep the edit timestamp correct even when a caller omits it or sends a stale value.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

create trigger articles_set_updated_at
    before update on public.articles
    for each row
    execute function public.set_updated_at();

alter table public.articles enable row level security;

revoke all on table public.articles from anon, authenticated;
grant select, insert, update, delete on table public.articles to service_role;
grant usage, select on sequence public.articles_id_seq to service_role;

revoke all on function public.set_updated_at() from public;
grant execute on function public.set_updated_at() to service_role;
