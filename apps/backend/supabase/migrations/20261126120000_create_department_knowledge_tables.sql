create table public.paid_services (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('tariff', 'booking_rule', 'payment_rule')),
    title text not null check (btrim(title) <> ''),
    body text check (btrim(body) <> ''),
    section text,
    audience text,
    unit text,
    price_label text,
    price_type text check (price_type in ('fixed', 'from', 'range')),
    amount numeric(14, 2) check (amount >= 0 and amount < 'Infinity'::numeric),
    max_amount numeric(14, 2) check (max_amount >= amount and max_amount < 'Infinity'::numeric),
    effective_from date,
    embedding extensions.vector(768) check (extensions.vector_norm(embedding) > 0),
    constraint paid_services_entry_check check (
        (kind = 'tariff' and price_type is not null and amount is not null
            and ((price_type = 'range') = (max_amount is not null)))
        or (kind <> 'tariff' and body is not null and price_type is null
            and amount is null and max_amount is null and effective_from is null)
    )
);

create table public.research_department (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('research_area', 'project', 'publication', 'contact')),
    title text not null check (btrim(title) <> ''),
    body text not null check (btrim(body) <> ''),
    embedding extensions.vector(768) check (extensions.vector_norm(embedding) > 0)
);

create table public.clinical_department (
    id bigint generated by default as identity primary key,
    kind text not null check (kind in ('unit', 'specialist', 'schedule', 'admission_rule', 'contact')),
    title text not null check (btrim(title) <> ''),
    body text not null check (btrim(body) <> ''),
    embedding extensions.vector(768) check (extensions.vector_norm(embedding) > 0)
);

create trigger clear_paid_service_embedding
before update on public.paid_services
for each row when (
    old.embedding is not null and
    (old.title, old.body, old.section, old.audience, old.unit, old.price_label) is distinct from
    (new.title, new.body, new.section, new.audience, new.unit, new.price_label)
)
execute function public.clear_knowledge_embedding();

create trigger clear_research_department_embedding
before update on public.research_department
for each row when (
    old.embedding is not null and (old.title, old.body) is distinct from (new.title, new.body)
)
execute function public.clear_knowledge_embedding();

create trigger clear_clinical_department_embedding
before update on public.clinical_department
for each row when (
    old.embedding is not null and (old.title, old.body) is distinct from (new.title, new.body)
)
execute function public.clear_knowledge_embedding();

alter table public.paid_services enable row level security;
alter table public.research_department enable row level security;
alter table public.clinical_department enable row level security;

revoke all on table public.paid_services, public.research_department, public.clinical_department
    from public, anon, authenticated;
revoke all on sequence public.paid_services_id_seq, public.research_department_id_seq,
    public.clinical_department_id_seq from public, anon, authenticated;
grant select, insert, update, delete on table public.paid_services, public.research_department,
    public.clinical_department to service_role;
grant usage, select on sequence public.paid_services_id_seq, public.research_department_id_seq,
    public.clinical_department_id_seq to service_role;
